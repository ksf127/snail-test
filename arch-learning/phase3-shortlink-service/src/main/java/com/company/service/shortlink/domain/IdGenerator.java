package com.company.service.shortlink.domain;

/**
 * 发号器：为每条新短链分配一个全局唯一的数字 ID。
 *
 * <p>【解决什么问题】短码必须能从数字 ID 唯一地编码出来（见 {@link Base62}），
 * 所以系统需要一个"绝不会发出重复号码"的序列。去掉它，就只能靠数据库自增或随机数：
 * 前者把写路径锁在同一张表上，后者要靠冲突重试，都不适合短链这种"先算短码再落库"的模型。
 *
 * <p>【为什么这样设计】短链场景只有创建时才需要发号，QPS 远低于跳转，
 * 但一旦重复发号，两条短链会指向同一个短码，是资损级事故。
 * 因此这里把<b>唯一性优先级放在吞吐之上</b>：允许浪费号码（进程重启丢掉未用完的号段），
 * 但绝不允许重复。这也是选择"号段模式"而不是"雪花 ID"的核心原因 ——
 * 雪花 ID 依赖机器时钟，回拨会产生重复或乱序，而号段由存储端原子自增，天然单调唯一。
 *
 * <p>【怎么读这段代码】接口只有一个方法，实现见 {@link SegmentIdGenerator}。
 */
public interface IdGenerator {

    /**
     * 取下一个全局唯一 ID。
     *
     * <p>实现必须保证任意并发调用下不返回重复值，并且同一实例内单调递增。
     *
     * @return 全局唯一的数字 ID，可直接交给 {@link Base62#encodeFixed(long)}
     * @throws IllegalStateException 号段耗尽或号段来源返回非法数据时
     */
    long nextId();
}
