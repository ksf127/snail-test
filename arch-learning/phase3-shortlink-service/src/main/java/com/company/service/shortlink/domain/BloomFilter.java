package com.company.service.shortlink.domain;

/**
 * 布隆过滤器：用极小的内存把"一定不存在"的请求挡在缓存和数据库之前。
 *
 * <p>【解决什么问题】100 万 QPS 里混着大量随机扫描、爬虫、以及已删除的短码。
 * 这些请求如果都走到 L2 缓存和数据库，缓存会被无用 key 挤占，数据库会被无意义查询打满。
 * 布隆过滤器用每个 key 约十几 bit 的内存，给出"一定不存在 / 可能存在"的判断，
 * 把前者直接挡在链路最前面 —— 去掉它，抗随机扫描的能力就完全消失了。
 *
 * <p>【为什么这样设计】放在缓存<b>前面</b>而不是后面：
 * <ul>
 *   <li>它的单次判断是纯内存位运算，比一次 Redis 往返快一到两个数量级，所以能挡在最外层；</li>
 *   <li>布隆只允许"假阳性"（说不存在时一定不存在；说可能存在时可能不存在），
 *       绝不漏判，因此不会把真实存在的短链误杀；</li>
 *   <li>标准布隆不支持删除，短链删除后仍可能通过布隆，由缓存 + 数据库兜底，
 *       这是刻意接受的代价，换来的是一次判断零 IO。</li>
 * </ul>
 *
 * <p>【怎么读这段代码】只有两个动作：{@link #add(String)} 在创建短链时登记，
 * {@link #mightContain(String)} 在读取时判否。两个实现的差异只在存储介质：
 * 内存版单进程、重启即丢（需要 {@code BloomWarmUp} 预热），Redis 版多实例共享、可持久化。
 */
public interface BloomFilter {

    /**
     * 判断 key 是否可能存在。
     *
     * <p>false 是确定结论：一定没加过；true 只是"可能"。
     * 实现必须是线程安全的，因为同一实例会被大量请求线程并发调用。
     *
     * @param key 短码
     * @return 可能存在返回 true，一定不存在返回 false
     */
    boolean mightContain(String key);

    /**
     * 把 key 登记进位图。
     *
     * <p>必须可被多线程并发调用；重复添加同一个 key 不改变结果（幂等）。
     *
     * @param key 短码
     */
    void add(String key);
}
